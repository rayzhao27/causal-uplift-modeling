SELECT
  treatment,
  COUNT(*) AS n,
  AVG(age) AS mean_age,
  STDDEV_SAMP(age) AS std_age,
  AVG(tenure_months) AS mean_tenure_months,
  STDDEV_SAMP(tenure_months) AS std_tenure_months,
  AVG(prior_purchases) AS mean_prior_purchases,
  STDDEV_SAMP(prior_purchases) AS std_prior_purchases,
  AVG(prior_spend) AS mean_prior_spend,
  STDDEV_SAMP(prior_spend) AS std_prior_spend,
  AVG(recency_days) AS mean_recency_days,
  STDDEV_SAMP(recency_days) AS std_recency_days,
  AVG(sessions_30d) AS mean_sessions_30d,
  STDDEV_SAMP(sessions_30d) AS std_sessions_30d,
  AVG(email_opens_30d) AS mean_email_opens_30d,
  STDDEV_SAMP(email_opens_30d) AS std_email_opens_30d,
  AVG(pages_viewed_30d) AS mean_pages_viewed_30d,
  STDDEV_SAMP(pages_viewed_30d) AS std_pages_viewed_30d,
  AVG(avg_order_value) AS mean_avg_order_value,
  STDDEV_SAMP(avg_order_value) AS std_avg_order_value,
  AVG(discount_sensitivity) AS mean_discount_sensitivity,
  STDDEV_SAMP(discount_sensitivity) AS std_discount_sensitivity,
  AVG(is_loyalty_member) AS mean_is_loyalty_member,
  STDDEV_SAMP(is_loyalty_member) AS std_is_loyalty_member,
  AVG(is_weekend_shopper) AS mean_is_weekend_shopper,
  STDDEV_SAMP(is_weekend_shopper) AS std_is_weekend_shopper,
  AVG(device_mobile) AS mean_device_mobile,
  STDDEV_SAMP(device_mobile) AS std_device_mobile,
  AVG(device_desktop) AS mean_device_desktop,
  STDDEV_SAMP(device_desktop) AS std_device_desktop,
  AVG(exposure) AS mean_exposure,
  STDDEV_SAMP(exposure) AS std_exposure
FROM experiment
GROUP BY treatment
ORDER BY treatment;
